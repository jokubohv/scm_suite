#!/usr/bin/env bash
# provision_sso_dex.sh — render the per-connection Dex OIDC broker configuration for one company SSO.
#
# Usage: scripts/provision_sso_dex.sh --tenant TENANT --protocol SAML|OIDC|LDAP_AD [options]
#   --tenant TENANT             tenant slug (lower-case, used in the issuer host label)
#   --protocol P                company IdP protocol federated by Dex
#   --connection-id ID          SSO connection id (default: TENANT-PROTOCOL)
#   --issuer URL                public issuer URL (default: https://sso-TENANT.auth.example.com)
#   --client-id ID              platform API OIDC client id (default: inventory-platform)
#   --client-secret-ref REF     secret-manager reference ONLY (never a secret value)
#   --group-claim NAME          IdP groups claim (default: groups)
#   --output FILE               write rendered config to FILE (default: stdout)
#   --force                     overwrite an existing --output file
#   --check                     validate arguments/env expectations only (no rendering)
#   --dry-run                   print render plan + config without writing files
#
# Security: secrets are referenced (secret-manager ids) and injected at deploy time; this script never
# accepts or emits plaintext secrets. Phase-1 platform stores `*_secret_ref` pointers only.
# Rendering is deterministic/idempotent; the same inputs produce byte-identical output.
# Exits: 0 ok, 1 write/validation failure, 2 usage error, 3 missing dependency.
set -euo pipefail
# shellcheck source=scripts/_common.sh
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/_common.sh"

tenant=""
protocol=""
connection_id=""
issuer=""
client_id="inventory-platform"
client_secret_ref=""
group_claim="groups"
output=""
force=0
check=0
dry_run=0
while (($#)); do
  case "$1" in
    --tenant) tenant="${2:-}"; shift 2 ;;
    --protocol) protocol="${2:-}"; shift 2 ;;
    --connection-id) connection_id="${2:-}"; shift 2 ;;
    --issuer) issuer="${2:-}"; shift 2 ;;
    --client-id) client_id="${2:-}"; shift 2 ;;
    --client-secret-ref) client_secret_ref="${2:-}"; shift 2 ;;
    --group-claim) group_claim="${2:-}"; shift 2 ;;
    --output) output="${2:-}"; shift 2 ;;
    --force) force=1; shift ;;
    --check) check=1; shift ;;
    --dry-run) dry_run=1; shift ;;
    -h | --help) usage_header "${BASH_SOURCE[0]}" 0 ;;
    *) usage_header "${BASH_SOURCE[0]}" 2 ;;
  esac
  if (($# < 0)); then usage_header "${BASH_SOURCE[0]}" 2; fi
done
[[ -n "$tenant" && -n "$protocol" ]] || usage_header "${BASH_SOURCE[0]}" 2
[[ "$tenant" =~ ^[a-z0-9][a-z0-9-]{0,62}$ ]] || die "tenant must be a lower-case slug" 2
case "$protocol" in
  SAML | OIDC | LDAP_AD) ;;
  *) die "protocol must be one of SAML|OIDC|LDAP_AD" 2 ;;
esac
protocol_lc="$(printf '%s' "$protocol" | tr '[:upper:]' '[:lower:]')"
connection_id="${connection_id:-${tenant}-${protocol_lc}}"
issuer="${issuer:-https://sso-${tenant}.auth.example.com}"
client_secret_ref="${client_secret_ref:-secret://sso/${tenant}/${connection_id}/client-secret}"
case "$client_secret_ref" in
  secret://* | vault://* | aws-sm://*) ;;
  *) die "client-secret-ref must be a secret-manager reference (secret://…), never a literal secret" 2 ;;
esac
[[ "$client_id" =~ ^[A-Za-z0-9._:-]{1,128}$ ]] || die "invalid client id" 2
[[ "$group_claim" =~ ^[A-Za-z0-9._/-]{1,64}$ ]] || die "invalid group claim name" 2

log "render Dex config: tenant=$tenant connection=$connection_id protocol=$protocol issuer=$issuer"
log "secrets: refs only (client_secret_ref=${client_secret_ref}); no plaintext secret is read or written"
if ((check == 1)); then
  [[ "$issuer" =~ ^https?:// ]] || die "issuer must be an http(s) URL" 2
  log "argument/env check OK; secret manager must resolve: ${client_secret_ref}"
  exit 0
fi
if ((dry_run == 1)) && [[ -n "$output" ]]; then
  log "dry-run: would write $output"
  output=""
fi
if [[ "$protocol" == "SAML" ]]; then
  connector_note="# SAML connector: metadata URL / entity id / signing cert are secret-manager refs in connector_config"
elif [[ "$protocol" == "OIDC" ]]; then
  connector_note="# OIDC connector: upstream issuer + client id/secret refs are read from connector_config"
else
  connector_note="# LDAP connector: host/baseDN/bind secret refs + user/group search filters from connector_config"
fi

render() {
  cat <<YAML
# Generated by scripts/provision_sso_dex.sh — deterministic, no secrets (refs resolved at deploy time).
# Tenant: ${tenant} | Connection: ${connection_id} | Protocol: ${protocol} | Plan: v1.5.0 (Δ-SSO EXT)
issuer: ${issuer}
storage:
  type: postgres
  config:
    host: \${DEX_DB_HOST:?DEX_DB_HOST is required}
    port: \${DEX_DB_PORT:-5432}
    database: \${DEX_DB_NAME:-dex_${tenant}}
    user: \${DEX_DB_USER:?DEX_DB_USER is required}
    password: \${DEX_DB_PASSWORD:?resolved from the secret manager at deploy time}
    ssl:
      mode: \${DEX_DB_SSL_MODE:-require}
web:
  http: 0.0.0.0:5556
  allowedOrigins: ['https://${tenant}.app.example.com']
staticClients:
  - id: ${client_id}
    name: inventory-platform (tenant ${tenant})
    # Dex reads the client secret from the process environment (injected from ${client_secret_ref})
    secretEnv: DEX_CLIENT_SECRET
    redirectURIs:
      - ${issuer}/callback
      - \${PLATFORM_SSO_CALLBACK_URL:?PLATFORM_SSO_CALLBACK_URL is required}
connectors:
  - type: ${protocol_lc}
    id: ${connection_id}
    name: ${tenant} ${protocol}
    ${connector_note}
    config:
      # Connector-specific fields are rendered from tenant_sso_connection.connector_config by the
      # integrator/ops job; secret values are env/secret-manager refs, never literals.
      groupClaim: ${group_claim}
      tenantHint: ${tenant}
YAML
}

if [[ -n "$output" ]]; then
  mkdir -p -- "$(dirname -- "$output")"
  tmp="$(mktemp "${output}.tmp.XXXXXX")"
  render >"$tmp"
  if [[ -e "$output" ]] && cmp -s "$tmp" "$output"; then
    rm -f "$tmp"
    log "unchanged (idempotent no-op): $output"
    exit 0
  fi
  if [[ -e "$output" && "$force" -eq 0 ]]; then
    rm -f "$tmp"
    die "output exists and differs: $output (pass --force to overwrite; rendering is deterministic)" 1
  fi
  mv -- "$tmp" "$output"
  log "wrote $output"
else
  render
fi
if ((dry_run == 1)); then
  log "dry-run complete (no file/secret changes)"
fi
