"""FS-12 residual: every contract-declared quality operation is mounted, scoped and canonical.

The frozen FS-12 fragment declares canonical ``{id}`` placeholders; the runtime mounts equivalent
resource-specific routes plus behaviour-preserving ``{id}`` aliases and the three collection-level PATCH
operations. This suite proves the declared<->mounted surface is complete and exercises representative
canonical/auth/tenant/validation behaviour.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any
from uuid import uuid4

import httpx
import pytest
from fastapi import FastAPI

from app.api.deps import Principal, get_current_principal, get_db
from app.api.errors import install_error_handlers
from app.api.routers.quality import ROUTE_SCOPES, router

pytestmark = pytest.mark.integration

REPO_ROOT = Path(__file__).resolve().parents[4]
FRAGMENT = REPO_ROOT / "contracts" / "openapi" / "fragments" / "FS-12.openapi.json"
CATALOGUE = {
    entry["scope"]
    for entry in json.loads((REPO_ROOT / "design" / "permissions.json").read_text(encoding="utf-8"))["catalogue"]
}
ALL_SCOPES = frozenset(CATALOGUE & {scope for scope in CATALOGUE if scope.startswith("quality.")})


def _declared() -> dict[tuple[str, str], dict[str, Any]]:
    fragment = json.loads(FRAGMENT.read_text(encoding="utf-8"))
    return {
        (method.upper(), path): operation
        for path, item in fragment["paths"].items()
        for method, operation in item.items()
        if method in {"get", "post", "put", "patch", "delete"}
    }


def _mounted() -> dict[tuple[str, str], Any]:
    return {
        (method.upper(), route.path): route
        for route in router.routes
        for method in getattr(route, "methods", set())
        if method in {"GET", "POST", "PUT", "PATCH", "DELETE"}
    }


def test_every_declared_fs12_operation_is_mounted() -> None:
    declared, mounted = _declared(), _mounted()
    assert sorted(set(declared) - set(mounted)) == []
    assert len(declared) == len(mounted) == len(ROUTE_SCOPES) == 57
    for operation, spec in declared.items():
        assert spec.get("x-feature-set") == "FS-12", operation
        # The aggregate skeleton is regenerated by the integrator; operations it has already marked
        # implementation-backed must remain so, the canonical aliases must never re-declare skeletons.
        if "x-implemented" in spec:
            assert spec["x-implemented"] is True, operation


def test_every_fs12_operation_has_one_catalogued_scope() -> None:
    for operation, route in _mounted().items():
        scope = ROUTE_SCOPES[operation]
        assert scope in CATALOGUE, (operation, scope)
        assert getattr(route, "dependencies", None), operation
    assert {scope for scope in ROUTE_SCOPES.values()} <= CATALOGUE


def test_canonical_id_paths_and_collection_patches_are_present() -> None:
    canonical = {operation for operation in _declared() if "{id}" in operation[1]}
    assert len(canonical) >= 18
    for operation in canonical:
        assert operation in ROUTE_SCOPES, operation
    for operation in (
        ("PATCH", "/api/v1/quality/inspection-plans"),
        ("PATCH", "/api/v1/quality/inspection-queues"),
        ("PATCH", "/api/v1/quality/inspection-triggers"),
    ):
        assert operation in _mounted(), operation


async def test_representative_canonical_routes(client: Any, seeded: dict[str, Any]) -> None:
    from app.tests.integration.quality.conftest import create_active_spec, create_inspection, create_plan

    spec = await create_active_spec(client, seeded["item_id"])
    detail = await client.get(f"/api/v1/quality/specs/{spec['id']}")
    assert detail.status_code == 200, detail.text
    plan = await create_plan(client, spec["id"], seeded["item_id"])
    inspection = await create_inspection(client, seeded, plan["id"])
    inspection_detail = await client.get(f"/api/v1/quality/inspections/{inspection['id']}")
    assert inspection_detail.status_code == 200, inspection_detail.text
    unknown = await client.get(f"/api/v1/quality/specs/{uuid4()}")
    assert unknown.status_code == 404, unknown.text


async def test_collection_level_patch_operations(client: Any, seeded: dict[str, Any]) -> None:
    from app.tests.integration.quality.conftest import create_active_spec, create_plan, idem

    spec = await create_active_spec(client, seeded["item_id"])
    plan = await create_plan(client, spec["id"], seeded["item_id"])
    patched_plan = await client.patch(
        "/api/v1/quality/inspection-plans", json={"id": plan["id"], "name": "Renamed plan"}
    )
    assert patched_plan.status_code == 200, patched_plan.text
    assert patched_plan.json()["plan"]["name"] == "Renamed plan"
    queue = await client.post(
        "/api/v1/quality/inspection-queues",
        json={"code": "Q-1", "name": "Queue 1", "assignment_strategy": "MANUAL"},
        headers=idem(),
    )
    assert queue.status_code == 201, queue.text
    patched_queue = await client.patch(
        "/api/v1/quality/inspection-queues", json={"id": queue.json()["queue"]["id"], "name": "Renamed queue"}
    )
    assert patched_queue.status_code == 200, patched_queue.text
    assert patched_queue.json()["queue"]["name"] == "Renamed queue"
    trigger = await client.post(
        "/api/v1/quality/inspection-triggers",
        json={"inspection_plan_id": plan["id"], "trigger_event": "ITEM_RECEIPT", "priority": 1},
        headers=idem(),
    )
    assert trigger.status_code == 201, trigger.text
    patched_trigger = await client.patch(
        "/api/v1/quality/inspection-triggers", json={"id": trigger.json()["trigger"]["id"], "priority": 2}
    )
    assert patched_trigger.status_code == 200, patched_trigger.text
    assert patched_trigger.json()["trigger"]["priority"] == 2
    missing_id = await client.patch("/api/v1/quality/inspection-plans", json={"name": "no id"})
    assert missing_id.status_code == 422, missing_id.text


async def _anonymous_client(db_session: Any) -> httpx.AsyncClient:
    app = FastAPI()
    install_error_handlers(app)
    app.include_router(router)

    async def _override_db() -> Any:
        yield db_session

    app.dependency_overrides[get_db] = _override_db
    return httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://testserver")


async def test_canonical_routes_require_authentication(db_session: Any) -> None:
    async with await _anonymous_client(db_session) as anonymous:
        response = await anonymous.get(f"/api/v1/quality/specs/{uuid4()}")
    assert response.status_code in {401, 403}, response.text


async def test_canonical_routes_are_tenant_scoped(
    db_session: Any, seeded: dict[str, Any], principal: Principal
) -> None:
    from sqlalchemy import insert

    from app.core.models import platform as platform_models
    from app.tests.integration.quality.conftest import create_active_spec

    other_tenant = uuid4()
    await db_session.execute(
        insert(platform_models.tenant).values(
            id=other_tenant, tenant_id=other_tenant, code=f"OTH{other_tenant.hex[:6]}",
            name="Other tenant", timezone="UTC", status="ACTIVE",
        )
    )
    await db_session.execute(
        insert(platform_models.feature_flag).values(
            id=uuid4(), tenant_id=other_tenant, flag_key="quality.management.enabled",
            is_enabled=True, source="TEST",
        )
    )
    app = FastAPI()
    install_error_handlers(app)
    app.include_router(router)

    async def _override_db() -> Any:
        yield db_session

    other_principal = Principal(
        identity_id=str(uuid4()), app_user_id=str(uuid4()), tenant_id=str(other_tenant),
        token_version=0, scopes=ALL_SCOPES,
    )
    app.dependency_overrides[get_db] = _override_db
    app.dependency_overrides[get_current_principal] = lambda: other_principal
    async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://testserver") as other:
        own_app = FastAPI()
        install_error_handlers(own_app)
        own_app.include_router(router)
        own_app.dependency_overrides[get_db] = _override_db
        own_app.dependency_overrides[get_current_principal] = lambda: principal
        async with httpx.AsyncClient(transport=httpx.ASGITransport(app=own_app), base_url="http://testserver") as own:
            spec = await create_active_spec(own, seeded["item_id"])
            foreign = await other.get(f"/api/v1/quality/specs/{spec['id']}")
    assert foreign.status_code == 404, foreign.text
